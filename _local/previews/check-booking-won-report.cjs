const { chromium } = require('C:/Users/angela/AppData/Local/npm-cache/_npx/420ff84f11983ee5/node_modules/playwright');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    let html = fs.readFileSync('app/widget.html', 'utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '');
    html = html.replace(/<link[^>]*href="\.\/([^"?]+)"[^>]*>/g, (_, file) => '<style>' + fs.readFileSync(path.join('app', file), 'utf8') + '</style>');
    await page.setContent(html);
    await page.evaluate(() => document.querySelectorAll('[data-tab-panel]').forEach(el => el.hidden = el.id !== 'tab-bookings'));
    for (const file of ['excel-workbook', 'booking-won-report']) await page.addScriptTag({ path: 'app/scripts/' + file + '.js' });
    await page.evaluate(() => {
      window.reportMode = 'success';
      AccountingManagerApp.initBookingWonReport({ coql: async () => {
        await new Promise(resolve => setTimeout(resolve, 400));
        if (window.reportMode === 'error') throw Error('CRM unavailable');
        if (window.reportMode === 'empty') return [];
        return [{ Ezus_Project_ID: 'project-1', id: '616617000003010705', Booking_Won_Date: '2026-10-06', Deal_Name: 'Sample booking', MFSP_Reference: 'MFSP-001', Stage: 'Trip Accounting Closure', Travellers_Number: 4 }];
      } }, ['Pending Res Assignment', 'Trip Accounting Closure']);
    });
    await page.click('#booking-won-open');
    await page.fill('#booking-won-date', '2026-10-06');
    assert.equal(await page.locator('#booking-won-stages input:checked').count(), 2);
    await page.click('#booking-won-stage-summary');
    await page.click('#booking-won-stages-none');
    await page.click('#booking-won-generate');
    await page.waitForFunction(() => document.getElementById('booking-won-message').textContent === 'Select at least one booking stage.');
    await page.click('#booking-won-stage-summary');
    await page.check('#booking-won-stages input[value="Pending Res Assignment"]');
    await page.click('#booking-won-generate');
    await page.waitForFunction(() => document.getElementById('booking-won-message').textContent.startsWith('No bookings'));
    await page.click('#booking-won-stage-summary');
    await page.click('#booking-won-stages-all');
    await page.click('#booking-won-stage-summary');
    await page.click('#booking-won-generate');
    assert.equal(await page.locator('#booking-won-loading').isVisible(), true);
    await page.locator('#booking-won-loading').screenshot({ path: '_local/previews/booking-won-loading.png' });
    await page.waitForFunction(() => !document.getElementById('booking-won-export-sales').disabled);
    assert.equal(await page.locator('#booking-won-loading').isHidden(), true);
    assert.equal(await page.locator('#booking-won-sales-table tbody tr').count(), 1);
    assert.equal(await page.locator('#booking-won-invoices-table tbody tr td').count(), 47);
    const pending = page.waitForEvent('download');
    await page.click('#booking-won-export-sales');
    const download = await pending;
    assert.equal(download.suggestedFilename(), 'VENTAS-2026-10-06.xlsx');
    const invoicesPending = page.waitForEvent('download');
    await page.click('#booking-won-export-invoices');
    const invoices = await invoicesPending;
    assert.equal(invoices.suggestedFilename(), 'RELACION-FACTURAS-2026-10-06.xlsx');
    await invoices.saveAs('_local/previews/booking-won-invoices-sample.xlsx');
    await download.saveAs('_local/previews/booking-won-sample.xlsx');
    assert.match(await page.textContent('#booking-won-message'), /1 bookings exported/);
    await page.locator('#booking-won-panel').screenshot({ path: '_local/previews/booking-won-1440.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#booking-won-panel').screenshot({ path: '_local/previews/booking-won-390.png' });
    assert.equal(await page.evaluate(() => document.getElementById('booking-won-panel').scrollWidth <= document.getElementById('booking-won-panel').clientWidth + 1), true);
    await page.fill('#booking-won-date', '2026-10-07');
    assert.equal(await page.locator('#booking-won-export-sales').isDisabled(), true);
    assert.equal(await page.locator('#booking-won-results').isHidden(), true);
    await page.fill('#booking-won-date', '2026-10-06');
    await page.evaluate(() => window.reportMode = 'empty');
    await page.click('#booking-won-generate');
    await page.waitForFunction(() => document.getElementById('booking-won-message').textContent.startsWith('No bookings'));
    await page.evaluate(() => window.reportMode = 'error');
    await page.click('#booking-won-generate');
    await page.waitForFunction(() => document.getElementById('booking-won-message').textContent === 'CRM unavailable');
    assert.equal(await page.locator('#booking-won-export-sales').isDisabled(), true);
    assert.equal(await page.locator('#booking-won-results').isHidden(), true);
    console.log('Browser checks passed: download, desktop/mobile layout, empty state, CRM failure.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
