    function onInvoicePaymentHeaderAccountKeydown(event) {
      var filteredAccounts;

      if (!event) {
        return;
      }

      if (event.key === "Enter") {
        filteredAccounts = getFilteredHeaderPaymentAccounts(state.paymentCreation.form.headerPaymentAccountQuery);
        if (filteredAccounts.length) {
          event.preventDefault();
          selectInvoicePaymentHeaderAccount(filteredAccounts[0].id);
        }
        return;
      }

      if (event.key === "Escape") {
        closeInvoicePaymentHeaderAccountDropdown();
        renderInvoicePaymentPanel();
        return;
      }

      if (event.key === "ArrowDown") {
        state.paymentCreation.form.headerPaymentAccountDropdownOpen = true;
        renderInvoicePaymentPanel();
      }
    }

