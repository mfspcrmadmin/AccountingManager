    function getAllowedPaymentAccountsForSupplier(supplierId) {
      var normalizedSupplierId = String(supplierId || "").trim();
      var allowedAccounts = state.records.paymentAccounts.filter(isSelectablePaymentAccount);

      return allowedAccounts.filter(function (account) {
        var ownerSupplierId = getPaymentAccountOwnerSupplierId(account);

        if (paymentAccountBelongsToSupplier(account, supplierId, "")) {
          return true;
        }

        if (!ownerSupplierId) {
          return true;
        }

        return normalizedSupplierId && ownerSupplierId === normalizedSupplierId;
      }).sort(function (left, right) {
        return getHeaderPaymentAccountOptionLabel(left).localeCompare(getHeaderPaymentAccountOptionLabel(right), "en", {
          sensitivity: "base"
        });
      });
    }

    function getPreferredPaymentAccountIdForSupplier(supplierId) {
      var normalizedSupplierId = String(supplierId || "").trim();
      var supplierRecord;
      var defaultPaymentAccountId;
      var supplierAccounts;
      var normalizedPaymentAccountId;
      var paymentAccountRecord;

      if (!normalizedSupplierId) {
        return "";
      }

      supplierRecord = getSupplierRecordById(supplierId);
      defaultPaymentAccountId = getSupplierDefaultPaymentAccountId(supplierRecord);

      if (defaultPaymentAccountId && getAllowedPaymentAccountsForSupplier(supplierId).some(function (account) {
        return String(account && account.id || "") === String(defaultPaymentAccountId);
      })) {
        return defaultPaymentAccountId;
      }

      supplierAccounts = getAllowedPaymentAccountsForSupplier(supplierId).filter(function (account) {
        return paymentAccountBelongsToSupplier(account, supplierId, "");
      });

      if (supplierAccounts.length) {
        return String(supplierAccounts[0].id || "");
      }

      if (supplierRecord) {
        normalizedPaymentAccountId = String(defaultPaymentAccountId || "").trim();
        if (normalizedPaymentAccountId) {
          paymentAccountRecord = getPaymentAccountRecordById(normalizedPaymentAccountId);
          if (paymentAccountRecord) {
            return normalizedPaymentAccountId;
          }
        }
      }

      return "";
    }

    function getSupplierPaymentAccountPlaceholder(supplierContext, accounts) {
      var supplierAccounts = (accounts || []).filter(function (account) {
        return paymentAccountBelongsToSupplier(
          account,
          supplierContext && supplierContext.id ? supplierContext.id : "",
          supplierContext && supplierContext.name ? supplierContext.name : ""
        );
      });

      if (!supplierContext || !supplierContext.id) {
        return "No supplier record available";
      }

      if (supplierAccounts.length) {
        return "Auto-assign supplier payment account";
      }

      if ((accounts || []).length) {
        return "Auto-create or choose shared account";
      }

      return "Auto-create supplier payment account";
    }

