    function buildInvoicePaymentContext(selectedInvoices) {
      var blockedStatuses = [];
      var zeroPendingInvoices = [];
      var normalInvoiceNumbers = [];
      var creditNoteInvoiceNumbers = [];
      var context;
      var supplierContextsByKey = {};

      if (!selectedInvoices || !selectedInvoices.length) {
        return {
          error: "Select at least one invoice with the checkbox before creating a payment."
        };
      }

      context = {
        supplierId: "",
        supplierName: "",
        bookingId: "",
        bookingName: "",
        settlementId: "",
        settlementName: "",
        ezusReference: "",
        supplierIds: [],
        supplierNames: [],
        bookingIds: [],
        bookingNames: [],
        settlementIds: [],
        settlementNames: [],
        mfsps: [],
        ezusReferences: [],
        suppliers: [],
        invoices: [],
        invoiceCount: selectedInvoices.length,
        totalAmount: 0
      };

      selectedInvoices.forEach(function (invoice) {
        var invoiceNumber = helpers.getInvoiceDisplayNumber(invoice, FIELD_CANDIDATES);
        var pendingAmount = roundCurrency(helpers.getInvoicePendingAmount(invoice, FIELD_CANDIDATES));
        var status = String(invoice.Status || "");
        var invoiceType = getInvoiceType(invoice);
        var isCreditNote = isCreditNoteInvoice(invoice);
        var supplierId = getInvoiceSupplierId(invoice);
        var supplierName = getSupplierNameFromInvoice(invoice);
        var bookingId = getBookingIdFromInvoice(invoice);
        var bookingName = getBookingNameFromInvoice(invoice) || "";
        var settlementId = getInvoiceSettlementId(invoice);
        var settlementName = getInvoiceSettlementName(invoice) || "";
        var mfsp = getMfspFromInvoice(invoice) || "";
        var ezusReference = invoice.Ezus_Supplier_Reference || "";
        var supplierContextKey = supplierId || (supplierName ? "supplier-name:" + supplierName : "invoice:" + invoice.id);
        var supplierContext;

        if (isBlockedInvoicePaymentStatus(status)) {
          blockedStatuses.push(invoiceNumber + " (" + helpers.textValue(status) + ")");
        }

        if (pendingAmount <= 0) {
          zeroPendingInvoices.push(invoiceNumber);
        }

        if (isCreditNote) {
          creditNoteInvoiceNumbers.push(invoiceNumber);
        } else {
          normalInvoiceNumbers.push(invoiceNumber);
        }

        if (supplierId) {
          context.supplierIds.push(supplierId);
        }
        if (supplierName) {
          context.supplierNames.push(supplierName);
        }
        if (bookingId) {
          context.bookingIds.push(bookingId);
        }
        if (bookingName) {
          context.bookingNames.push(bookingName);
        }
        if (settlementId) {
          context.settlementIds.push(settlementId);
        }
        if (settlementName) {
          context.settlementNames.push(settlementName);
        }
        if (mfsp) {
          context.mfsps.push(mfsp);
        }
        if (ezusReference) {
          context.ezusReferences.push(ezusReference);
        }

        if (!supplierContextsByKey[supplierContextKey]) {
          supplierContextsByKey[supplierContextKey] = {
            key: supplierContextKey,
            id: supplierId,
            name: supplierName || "Unknown supplier",
            bookingNames: [],
            settlementNames: [],
            mfsps: [],
            invoiceIds: [],
            invoiceNumbers: [],
            invoiceCount: 0,
            totalAmount: 0
          };
        }

        supplierContext = supplierContextsByKey[supplierContextKey];
        supplierContext.bookingNames.push(bookingName);
        supplierContext.settlementNames.push(settlementName);
        supplierContext.mfsps.push(mfsp);
        supplierContext.invoiceIds.push(invoice.id);
        supplierContext.invoiceNumbers.push(invoiceNumber);
        supplierContext.invoiceCount += 1;
        supplierContext.totalAmount += pendingAmount;

        context.invoices.push({
          id: invoice.id,
          number: invoiceNumber,
          invoiceType: invoiceType,
          isCreditNote: isCreditNote,
          date: invoice.Invoice_Date,
          supplierId: supplierId,
          supplierName: supplierName,
          bookingName: bookingName,
          settlementName: settlementName,
          mfsp: mfsp,
          pendingAmount: pendingAmount
        });
        context.totalAmount += pendingAmount;
      });

      context.totalAmount = roundCurrency(context.totalAmount);
      context.supplierIds = getUniqueSortedValues(context.supplierIds);
      context.supplierNames = getUniqueSortedValues(context.supplierNames);
      context.bookingIds = getUniqueSortedValues(context.bookingIds);
      context.bookingNames = getUniqueSortedValues(context.bookingNames);
      context.settlementIds = getUniqueSortedValues(context.settlementIds);
      context.settlementNames = getUniqueSortedValues(context.settlementNames);
      context.mfsps = getUniqueSortedValues(context.mfsps);
      context.ezusReferences = getUniqueSortedValues(context.ezusReferences);
      context.suppliers = Object.keys(supplierContextsByKey).map(function (key) {
        var supplierContext = supplierContextsByKey[key];

        supplierContext.bookingNames = getUniqueSortedValues(supplierContext.bookingNames);
        supplierContext.settlementNames = getUniqueSortedValues(supplierContext.settlementNames);
        supplierContext.mfsps = getUniqueSortedValues(supplierContext.mfsps);
        supplierContext.invoiceNumbers = getUniqueSortedValues(supplierContext.invoiceNumbers);
        supplierContext.totalAmount = roundCurrency(supplierContext.totalAmount);
        supplierContext.bookingDisplay = deps.getContextDisplayValue(supplierContext.bookingNames, "bookings", 3);
        supplierContext.settlementDisplay = deps.getContextDisplayValue(supplierContext.settlementNames, "settlements", 3);
        supplierContext.mfspDisplay = deps.getContextDisplayValue(supplierContext.mfsps, "MFSPs", 3);

        return supplierContext;
      }).sort(function (left, right) {
        return String(left.name || "").localeCompare(String(right.name || ""), "en", {
          sensitivity: "base"
        });
      });
      context.supplierId = context.supplierIds.length === 1 ? context.supplierIds[0] : "";
      context.supplierName = context.supplierNames.length === 1 ? context.supplierNames[0] : "";
      context.bookingId = context.bookingIds.length === 1 ? context.bookingIds[0] : "";
      context.bookingName = context.bookingNames.length === 1 ? context.bookingNames[0] : "";
      context.settlementId = context.settlementIds.length === 1 ? context.settlementIds[0] : "";
      context.settlementName = context.settlementNames.length === 1 ? context.settlementNames[0] : "";
      context.ezusReference = context.ezusReferences.length === 1 ? context.ezusReferences[0] : "";
      context.movementType = creditNoteInvoiceNumbers.length && !normalInvoiceNumbers.length
        ? PAYMENT_MOVEMENT_TYPES.supplierRefund
        : PAYMENT_MOVEMENT_TYPES.outbound;
      context.hasMixedInvoiceTypes = normalInvoiceNumbers.length > 0 && creditNoteInvoiceNumbers.length > 0;
      context.actionLabel = context.movementType === PAYMENT_MOVEMENT_TYPES.supplierRefund ? "refund" : "payment";
      context.contextMode = (
        context.supplierNames.length <= 1 &&
        context.bookingNames.length <= 1 &&
        context.settlementNames.length <= 1
      ) ? "Single" : "Mixed";
      context.contextSummary = buildPaymentContextSummaryText(context);
      context.supplierDisplay = deps.getContextDisplayValue(context.supplierNames, "suppliers");
      context.bookingDisplay = deps.getContextDisplayValue(context.bookingNames, "bookings");
      context.settlementDisplay = deps.getContextDisplayValue(context.settlementNames, "settlements");

      if (blockedStatuses.length) {
        return {
          error: "These invoices cannot be paid from this form because their status is not payable: " + blockedStatuses.join(", ") + "."
        };
      }

      if (zeroPendingInvoices.length) {
        return {
          error: "These invoices no longer have pending amount to allocate: " + zeroPendingInvoices.join(", ") + "."
        };
      }

      return {
        context: context
      };
    }

    function buildDefaultInvoicePaymentForm(context) {
      var allocations = {};
      var paymentAccountsBySupplier = {};
      var paymentDate = "";
      var defaultReference = buildDefaultPaymentReference(paymentDate);

      (context && context.invoices ? context.invoices : []).forEach(function (invoice) {
        allocations[invoice.id] = roundCurrency(invoice.pendingAmount);
      });

      (context && context.suppliers ? context.suppliers : []).forEach(function (supplierContext) {
        if (supplierContext.id) {
          paymentAccountsBySupplier[supplierContext.id] = getPreferredPaymentAccountIdForSupplier(supplierContext.id);
        }
      });

      return {
        name: defaultReference,
        lastAutoGeneratedName: defaultReference,
        paymentDate: paymentDate,
        headerPaymentAccountId: "",
        headerPaymentAccountQuery: "",
        headerPaymentAccountDropdownOpen: false,
        movementType: context && context.movementType ? context.movementType : PAYMENT_MOVEMENT_TYPES.outbound,
        status: "Paid",
        accountingStatus: "Pending",
        paymentAccountsBySupplier: paymentAccountsBySupplier,
        supplierAccountQueries: {},
        supplierAccountDropdownSupplierId: "",
        allocations: allocations
      };
    }

    function getInvoicePaymentSelectedAmount(context, allocations) {
      return roundCurrency((context && context.invoices ? context.invoices : []).reduce(function (sum, invoice) {
        var rawValue = allocations && allocations[invoice.id] !== undefined ? allocations[invoice.id] : invoice.pendingAmount;
        var parsedValue = Number(rawValue);
        return sum + (Number.isFinite(parsedValue) && parsedValue > 0 ? parsedValue : 0);
      }, 0));
    }

    function getInvoicePaymentNetAmount(context, allocations) {
      return roundCurrency((context && context.invoices ? context.invoices : []).reduce(function (sum, invoice) {
        var rawValue = allocations && allocations[invoice.id] !== undefined ? allocations[invoice.id] : invoice.pendingAmount;
        var parsedValue = Number(rawValue);
        var amount = Number.isFinite(parsedValue) && parsedValue > 0 ? parsedValue : 0;
        return sum + (invoice.isCreditNote ? -amount : amount);
      }, 0));
    }

    function getSupplierPaymentSelectedAmount(supplierContext, allocations, invoices) {
      return roundCurrency((invoices || []).reduce(function (sum, invoice) {
        var rawValue;
        var parsedValue;

        if (supplierContext && supplierContext.id) {
          if (String(invoice.supplierId || "") !== String(supplierContext.id)) {
            return sum;
          }
        } else if (String(invoice.supplierName || "") !== String(supplierContext && supplierContext.name || "")) {
          return sum;
        }

        rawValue = allocations && allocations[invoice.id] !== undefined ? allocations[invoice.id] : invoice.pendingAmount;
        parsedValue = Number(rawValue);
        return sum + (Number.isFinite(parsedValue) && parsedValue > 0 ? parsedValue : 0);
      }, 0));
    }

